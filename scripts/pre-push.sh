#!/bin/bash
# Хук для принудительного обновления контекста Second Brain
# Установка: ln -s ../../scripts/pre-push.sh .git/hooks/pre-push

# Проверяем, есть ли измененные файлы в journal/ за последние 7 дней
LATEST_JOURNAL=$(find journal/ -type f -mtime -7 2>/dev/null | head -n 1)

if [ -z "$LATEST_JOURNAL" ]; then
    echo "=========================================================================="
    echo "[БАРЬЕР]: Контекст не актуален!"
    echo "В папке 'journal/' нет свежих записей за последние 7 дней."
    echo "Пожалуйста, заполни journal/weekly.md или добавь лог сессии."
    echo "Brain's Protocol должен оставаться живой базой, а не мертвым архивом."
    echo ""
    echo "Для обхода блокировки используй: git push --no-verify"
    echo "=========================================================================="
    exit 1
fi

echo "[УСПЕХ] Контекст актуален. Разрешаю push."
exit 0
